"""
Generate src/data/problems.js from data/leetcode_problems.csv.

Usage:
    python scripts/build_problems.py

The CSV is the source of truth. Rows are expected to be pre-sorted by
frequency (highest first); each row's position becomes its rank/id.
"""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "leetcode_problems.csv"
OUT = ROOT / "src" / "data" / "problems.js"


def parse_row(index, row):
    return {
        "id": index + 1,
        "title": row["Title"].strip(),
        "difficulty": row["Difficulty"].strip().upper(),
        "frequency": float(row["Frequency"]),
        # The CSV stores acceptance as a fraction scaled by 1e-4 (0.0058 -> 58.0%)
        "acceptanceRate": round(float(row["Acceptance Rate"]) * 10000, 1),
        "link": row["Link"].strip(),
        "topics": [t.strip() for t in row["Topics"].split(",") if t.strip()],
    }


def main():
    with SRC.open(encoding="utf-8", newline="") as f:
        problems = [parse_row(i, r) for i, r in enumerate(csv.DictReader(f))]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(problems, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text(
        "// Auto-generated by scripts/build_problems.py from data/leetcode_problems.csv. Do not edit by hand.\n"
        f"export const PROBLEMS = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(problems)} problems to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
